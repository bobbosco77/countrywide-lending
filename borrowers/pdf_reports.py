PAGE_WIDTH = 595
PAGE_HEIGHT = 842


def company():
    return CompanySettings.objects.first()


def draw_header(pdf, title):

    c = company()

    if c and c.logo:
        try:
            logo = ImageReader(c.logo.path)

            pdf.drawImage(
                logo,
                40,
                PAGE_HEIGHT - 80,
                width=55,
                height=55,
                preserveAspectRatio=True,
                mask="auto"
            )
        except Exception:
            pass

    pdf.setFont("Helvetica-Bold", 18)

    pdf.drawString(
        110,
        PAGE_HEIGHT - 40,
        c.company_name if c else "COUNTRYWIDE LENDING & SERVICES"
    )

    pdf.setFont("Helvetica", 9)

    if c:

        if c.address:
            pdf.drawString(
                110,
                PAGE_HEIGHT - 56,
                c.address
            )

        if c.phone:
            pdf.drawString(
                110,
                PAGE_HEIGHT - 69,
                f"Phone: {c.phone}"
            )

        if c.email:
            pdf.drawString(
                110,
                PAGE_HEIGHT - 82,
                f"Email: {c.email}"
            )

    pdf.setStrokeColor(HexColor("#0B5ED7"))

    pdf.line(
        40,
        PAGE_HEIGHT - 96,
        PAGE_WIDTH - 40,
        PAGE_HEIGHT - 96
    )

    pdf.setFont("Helvetica-Bold", 15)

    pdf.drawCentredString(
        PAGE_WIDTH / 2,
        PAGE_HEIGHT - 118,
        title
    )

    pdf.setFont("Helvetica", 9)

    pdf.drawRightString(
        PAGE_WIDTH - 40,
        PAGE_HEIGHT - 118,
        date.today().strftime("%d %B %Y")
    )

    return 680


def draw_footer(pdf, request):

    c = company()

    pdf.line(
        40,
        60,
        PAGE_WIDTH - 40,
        60
    )

    pdf.setFont("Helvetica", 8)

    pdf.drawString(
        40,
        45,
        c.report_footer if c and c.report_footer else "Generated by CountryWide Lending System"
    )

    pdf.drawRightString(
        PAGE_WIDTH - 40,
        45,
        f"Printed by: {request.user.get_full_name() or request.user.username}"
    )

    pdf.drawCentredString(
        PAGE_WIDTH / 2,
        25,
        f"© {date.today().year} {c.company_name if c else 'CountryWide Lending'}"
    )

