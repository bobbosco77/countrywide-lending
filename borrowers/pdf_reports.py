def weekly_collection_pdf(request):

    today = timezone.now().date()
    start = today - timedelta(days=6)

    payments = (
        Payment.objects
        .filter(payment_date__range=[start, today])
        .order_by("payment_date")
    )

    response = HttpResponse(content_type="application/pdf")
    response["Content-Disposition"] = (
        f'attachment; filename="Weekly_Collection_{today}.pdf"'
    )

    pdf = canvas.Canvas(response)

    y = draw_header(pdf, "WEEKLY COLLECTION REPORT")

    pdf.setFont("Helvetica-Bold", 9)

    pdf.drawString(40, y, "Date")
    pdf.drawString(180, y, "Transactions")
    pdf.drawRightString(540, y, "Collections")

    y -= 12
    pdf.line(40, y, 555, y)

    y -= 18

    total = Decimal("0.00")

    for i in range(7):

        day = start + timedelta(days=i)

        daily = payments.filter(payment_date=day)

        amount = (
            daily.aggregate(
                total=Sum("amount_paid")
            )["total"]
            or Decimal("0.00")
        )

        count = daily.count()

        pdf.drawString(
            40,
            y,
            day.strftime("%A %d %b %Y")
        )

        pdf.drawString(
            200,
            y,
            str(count)
        )

        pdf.drawRightString(
            540,
            y,
            f"{{ company.currency_symbol }}{amount:,.2f}"
        )

        total += amount

        y -= 20

    y -= 10

    pdf.line(40, y, 555, y)

    y -= 20

    pdf.setFont("Helvetica-Bold", 11)

    pdf.drawString(
        40,
        y,
        "TOTAL WEEKLY COLLECTION"
    )

    pdf.drawRightString(
        540,
        y,
        f"{{ company.currency_symbol }}{total:,.2f}"
    )

    draw_footer(pdf, request)

    pdf.save()

    return response

def monthly_financial_report_pdf(request):

    today = timezone.now().date()

    loans = Loan.objects.filter(
        start_date__year=today.year,
        start_date__month=today.month,
    )

    payments = Payment.objects.filter(
        payment_date__year=today.year,
        payment_date__month=today.month,
    )

    response = HttpResponse(content_type="application/pdf")

    response["Content-Disposition"] = (
        f'Monthly_Financial_Report_{today}.pdf'
    )

    pdf = canvas.Canvas(response)

    y = draw_header(pdf, "MONTHLY FINANCIAL REPORT")

    loans_disbursed = (
        loans.aggregate(
            total=Sum("loan_amount")
        )["total"]
        or Decimal("0.00")
    )

    collections = (
        payments.aggregate(
            total=Sum("amount_paid")
        )["total"]
        or Decimal("0.00")
    )

    outstanding = sum(
        loan.balance()
        for loan in Loan.objects.all()
    )

    active = Loan.objects.filter(
        status="active"
    ).count()

    completed = Loan.objects.filter(
        status="completed"
    ).count()

    overdue = Loan.objects.filter(
        status="overdue"
    ).count()

    borrowers = Borrower.objects.count()

    pdf.setFont("Helvetica-Bold", 11)

    pdf.drawString(40, y, "Financial Summary")

    y -= 30

    pdf.setFont("Helvetica", 10)

    rows = [

        ("Loans Disbursed", f"{{ company.currency_symbol }}{loans_disbursed:,.2f}"),

        ("Collections Received", f"{{ company.currency_symbol }}{collections:,.2f}"),

        ("Outstanding Portfolio", f"{{ company.currency_symbol }}{outstanding:,.2f}"),

        ("Active Loans", str(active)),

        ("Completed Loans", str(completed)),

        ("Overdue Loans", str(overdue)),

        ("Registered Borrowers", str(borrowers)),

    ]

    for title, value in rows:

        pdf.drawString(
            50,
            y,
            title
        )

        pdf.drawRightString(
            540,
            y,
            value
        )

        y -= 22

    draw_footer(pdf, request)

    pdf.save()

    return response